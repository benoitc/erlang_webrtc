%% @doc CRC32c (Castagnoli) checksum used by SCTP (RFC 9260 Appendix A).
%%
%% `crc32c/1' returns the standard CRC32c value (reflected polynomial
%% `16#82F63B78', initial value and final XOR `16#FFFFFFFF'), so
%% `crc32c(<<"123456789">>) =:= 16#E3069283'.
%%
%% `update/2' continues a finalized value with more data:
%% `update(crc32c(A), B) =:= crc32c([A, B])' and
%% `crc32c(X) =:= update(0, X)'.
%%
%% SCTP computes the checksum over the whole packet with the checksum
%% field set to zero and stores it on the wire as `<<Crc:32/little>>'
%% (see `webrtc_sctp_chunk:encode/2' and `webrtc_sctp_chunk:checksum_ok/2').
%%
%% The implementation is pure Erlang, slicing-by-8 over eight 256 entry
%% tables kept as one literal tuple of 2048 entries (table K holds entry
%% N at index K * 256 + N + 1), with a byte loop for the tail.
-module(webrtc_sctp_crc32c).

-export([crc32c/1, update/2]).

-define(MASK32, 16#FFFFFFFF).

%% @doc CRC32c of `Data'.
-spec crc32c(iodata()) -> 0..16#FFFFFFFF.
crc32c(Data) ->
    update(0, Data).

%% @doc Continue the finalized CRC32c value `Crc' with `Data'.
-spec update(non_neg_integer(), iodata()) -> non_neg_integer().
update(Crc, Data) ->
    T = tab(),
    iodata_loop(Data, (Crc band ?MASK32) bxor ?MASK32, T) bxor ?MASK32.

iodata_loop(Bin, C, T) when is_binary(Bin) ->
    slice8(Bin, C, T);
iodata_loop([H | Tail], C, T) ->
    iodata_loop(Tail, iodata_loop(H, C, T), T);
iodata_loop([], C, _T) ->
    C;
iodata_loop(Byte, C, T) when is_integer(Byte), Byte >= 0, Byte =< 255 ->
    bytes(<<Byte>>, C, T).

slice8(<<W:32/little, B4, B5, B6, B7, Rest/binary>>, C, T) ->
    X = C bxor W,
    C1 =
        element((X band 16#FF) + 1793, T) bxor
            element(((X bsr 8) band 16#FF) + 1537, T) bxor
            element(((X bsr 16) band 16#FF) + 1281, T) bxor
            element((X bsr 24) + 1025, T) bxor
            element(B4 + 769, T) bxor
            element(B5 + 513, T) bxor
            element(B6 + 257, T) bxor
            element(B7 + 1, T),
    slice8(Rest, C1, T);
slice8(Rest, C, T) ->
    bytes(Rest, C, T).

bytes(<<B, Rest/binary>>, C, T) ->
    bytes(Rest, (C bsr 8) bxor element(((C bxor B) band 16#FF) + 1, T), T);
bytes(<<>>, C, _T) ->
    C.

